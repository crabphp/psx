<?php

declare(strict_types=1);

namespace Crab\Psx\Compiler;

use Crab\Contracts\Routing\Actions;
use Crab\Psx\PsxException;
use Crab\Psx\Registry\Declaration;
use Crab\Psx\Registry\Registry;

/**
 * Compiles an application's .psx files: the PHP of each into a private
 * folder beside a manifest, and the TSX of each, with the types and the
 * bindings the page is given, into the folder the JavaScript build reads.
 *
 * The PHP is loaded to read its types, which defines its classes: a
 * process compiles an application once. No loader, query or action is
 * run, and no Server class is made.
 *
 * @internal
 */
final class Compiler
{
    /**
     * Where a compile that does not publish keeps what the JavaScript build reads, inside its stage.
     */
    public const string BROWSER = 'browser';

    public const int PROTOCOL = 1;

    private const string BANNER = '// Generated by PSX. Do not edit: it is written again on every compile.';

    /**
     * @param string $base The application's folder.
     * @param string $resources The folder of its .psx files, relative to it.
     * @param string $client Where what the JavaScript build reads is written, relative to it: ".psx".
     * @param string $namespace The namespace the modules are compiled into.
     */
    public function __construct(
        private readonly string $base,
        private readonly string $resources,
        private readonly string $client,
        private readonly Actions $actions,
        private readonly string $namespace = Source::ROOT,
        private readonly ?string $wrapper = null,
    ) {}

    /**
     * Compiles into a folder, and gives the private manifest written there.
     *
     * @param string $stage The private folder, absolute.
     * @param bool $publish Whether what the JavaScript build reads is written where it reads it. Where it is not, it is kept in the stage for publish(), once the stage was found fit to serve: the scripts a browser is given and the server that answers them change together.
     * @return array<string, mixed>
     */
    public function compile(Registry $registry, string $stage, bool $publish = true): array
    {
        $sources = [];
        foreach ($this->files() as $file) {
            $code = file_get_contents("{$this->base}/{$file}");
            if ($code === false) {
                throw new PsxException('The file cannot be read.', $file);
            }
            $sources[$file] = Source::parse($file, $code, $this->resources, $this->namespace);
        }
        // PHP tells no class names apart by their case, and a file's punctuation is not a name's: two
        // files whose namespaces are one would declare each other's classes. Said before any is loaded.
        $spaces = [];
        foreach ($sources as $file => $source) {
            $space = strtolower($source->namespace);
            if (isset($spaces[$space])) {
                throw new PsxException(
                    "The file and {$spaces[$space]} are the same to PHP: both compile into the namespace {$source->namespace}, where a name's case and what is not a letter, a digit or \"_\" in a path tell nothing apart. Rename one of them.",
                    $file,
                );
            }
            $spaces[$space] = $file;
        }
        $declared = [];
        foreach ($registry->all() as $declaration) {
            if (!isset($sources[$declaration->file])) {
                throw new PsxException(
                    "{$declaration->label()} names a file outside the {$this->resources} folder, \"psx.resources\".",
                    $declaration->file,
                );
            }
            $kind = $declared[$declaration->file] ?? $declaration->kind;
            if ($kind !== $declaration->kind) {
                throw new PsxException(
                    "The file is declared as a {$kind} and as a {$declaration->kind}; it is one of them. What two share is a component both import.",
                    $declaration->file,
                );
            }
            $declared[$declaration->file] = $declaration->kind;
        }
        self::fresh("{$stage}/php");
        $modules = [];
        foreach ($sources as $file => $source) {
            if ($source->server && !isset($declared[$file])) {
                throw new PsxException(
                    'The file has a Server class and is not declared. Importing a component runs none of its PHP: declare it with $pages->service(...), or as a page or a layout.',
                    $file,
                );
            }
            if ($source->php !== null) {
                $path = "{$stage}/php/{$source->id}.php";
                self::write($path, $source->php);
                self::load($path, $source);
            }
            $modules[$file] = [
                'id' => $source->id,
                'php' => $source->php === null ? null : "php/{$source->id}.php",
                ...ModuleReader::read($source),
            ];
        }
        $families = Families::build($registry, $modules, $this->actions);
        $this->client(
            $sources,
            $modules,
            $declared,
            $families,
            $publish ? "{$this->base}/{$this->client}" : "{$stage}/" . self::BROWSER,
        );
        $hashes = [];
        foreach ($sources as $file => $source) {
            $hashes[$file] = hash('sha256', (string) $source->php);
        }
        $fingerprint = Families::fingerprint($families);
        $manifest = [
            'protocol' => self::PROTOCOL,
            'build' => Families::hash([self::PROTOCOL, $fingerprint, $hashes, $this->namespace]),
            'namespace' => $this->namespace,
            'fingerprint' => $fingerprint,
            'modules' => $modules,
        ];
        self::write("{$stage}/manifest.json", self::json($manifest));
        return $manifest;
    }

    /**
     * @return list<string> Every .psx file of the resources folder, relative to the application.
     */
    private function files(): array
    {
        $root = "{$this->base}/{$this->resources}";
        if (!is_dir($root)) {
            throw new PsxException(
                "There is no {$this->resources} folder, \"psx.resources\". `php cua psx:init` writes a first page.",
            );
        }
        $files = [];
        $iterator = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator(
            $root,
            \FilesystemIterator::SKIP_DOTS,
        ));
        foreach ($iterator as $file) {
            if ($file->isFile() && $file->getExtension() === 'psx') {
                $files[] = $this->resources . substr($file->getPathname(), strlen($root));
            }
        }
        sort($files);
        return $files;
    }

    /**
     * Loads a compiled module's PHP, so its types can be read.
     */
    private static function load(string $path, Source $source): void
    {
        try {
            (static function () use ($path): void {
                require $path;
            })();
        } catch (\ParseError $error) {
            throw new PsxException($error->getMessage() . '.', $source->file, $error->getLine(), $error);
        } catch (\Error $error) {
            throw new PsxException(
                $error->getMessage() . '.',
                $source->file,
                $error->getFile() === $path ? $error->getLine() : null,
                $error,
            );
        }
    }

    /**
     * Writes what the JavaScript build reads: no PHP, and nothing of
     * the server but the names and the types the page is given.
     *
     * @param array<string, Source> $sources
     * @param array<string, array<string, mixed>> $modules
     * @param array<string, string> $declared
     * @param array{routes: array<string, array<string, mixed>>, services: array<string, array<string, mixed>>} $families
     */
    private function client(array $sources, array $modules, array $declared, array $families, string $root): void
    {
        $mounts = [];
        $operations = [];
        foreach ($families['routes'] as $route) {
            foreach ($route['nodes'] as $node) {
                $mounts[$node['module']][] = $node['mount'];
            }
            foreach ($route['operations'] as $operation) {
                $operations[$operation['module']][$operation['method']][$operation['mount']] = $operation
                + ['path' => Families::segments($operation['pattern'])];
            }
        }
        $direct = [];
        foreach ($families['services'] as $service) {
            $mounts[$service['module']][] = $service['name'];
            $direct[$service['module']][] = $service;
            foreach ($service['operations'] as $operation) {
                $operations[$operation['module']][$operation['method']][$operation['mount']] = $operation
                + ['path' => Families::segments($operation['pattern'])];
            }
        }
        $files = [];
        $public = [];
        foreach ($sources as $file => $source) {
            $module = $modules[$file];
            $id = $source->id;
            $names = array_keys($module['operations']);
            $tsx = $source->tsx;
            foreach ($names as $name) {
                $binding = preg_quote('$' . $name, '/');
                if (
                    preg_match(
                        "/^.*(?:\\b(?:const|let|var|function|class)\\s+{$binding}\\b|\\bimport\\b[^;]*[{,\\s]{$binding}\\b[^;]*\\bfrom\\b).*$/m",
                        $tsx,
                        $found,
                        PREG_OFFSET_CAPTURE,
                    ) === 1
                ) {
                    throw new PsxException(
                        "The TSX declares \${$name}, which is the name the {$name}() of the Server class is given. Call the other one something else.",
                        $file,
                        substr_count($tsx, "\n", 0, $found[0][1]) + 1,
                    );
                }
            }
            $import = $names === []
                ? ''
                : 'import { '
                . implode(', ', array_map(static fn(string $name): string => '$' . $name, $names))
                . " } from '@psx/server/{$id}';";
            $files["client/{$id}.psx.tsx"] = $import . $tsx;
            if (!isset($declared[$file])) {
                continue;
            }
            $only = $direct[$id] ?? [];
            // A service mounted once, on a path without parameters, is called without a scope.
            $single =
                count($only) === 1 && count($mounts[$id]) === 1 && array_column($only[0]['segments'], 'name') === []
                    ? $only[0]['name']
                    : null;
            $files["types/{$id}.ts"] = $this->types(
                $module,
                $declared[$file],
                array_values(array_unique($mounts[$id] ?? [])),
                $operations[$id] ?? [],
            );
            $files["server/{$id}.ts"] = self::bindings($id, $module, $operations[$id] ?? [], $single);
            $files["client/{$id}.psx?server.ts"] = self::BANNER . "\nexport * from '@psx/server/{$id}';\n";
            foreach ($operations[$id] ?? [] as $method => $byMount) {
                $first = $byMount[array_key_first($byMount)];
                $public[$id][$method] = [
                    'role' => $first['role'],
                    'mode' => $first['files'] ? 'form' : 'both',
                    'auth' => $first['auth'],
                    'shape' => self::bare($first['shape']),
                    'mounts' => array_map(static fn(array $operation): array => [
                        'id' => $operation['id'],
                        'schema' => $operation['schema'],
                        'path' => $operation['path'],
                    ], $byMount),
                ];
            }
        }
        $files['routes.ts'] = self::routes($families['routes']);
        $files['services.ts'] = self::services($families['services']);
        $files['manifest.ts'] = $this->manifest($families, $public, $sources);
        foreach ($files as $path => $content) {
            self::write("{$root}/{$path}", $content);
        }
        self::prune($root, array_keys($files));
    }

    /**
     * Writes what a compile kept in its stage where the JavaScript build
     * reads it: each file that changed, and no longer those it dropped.
     */
    public function publish(string $stage): void
    {
        $from = "{$stage}/" . self::BROWSER;
        if (!is_dir($from)) {
            return;
        }
        $root = "{$this->base}/{$this->client}";
        $kept = [];
        $iterator = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator(
            $from,
            \FilesystemIterator::SKIP_DOTS,
        ));
        foreach ($iterator as $file) {
            if ($file->isFile()) {
                $path = substr($file->getPathname(), strlen($from) + 1);
                $kept[] = $path;
                self::write("{$root}/{$path}", (string) file_get_contents($file->getPathname()));
            }
        }
        self::prune($root, $kept);
    }

    /**
     * A module's types: its data, its props, and what each of its
     * queries and actions takes and gives.
     *
     * @param array<string, mixed> $module
     * @param list<string> $mounts
     * @param array<string, array<string, array<string, mixed>>> $operations
     */
    private function types(array $module, string $kind, array $mounts, array $operations): string
    {
        $reserved = ['Data', 'Props', 'Mounts'];
        foreach (array_keys($operations) as $method) {
            $reserved[] = ucfirst($method) . 'Input';
            $reserved[] = ucfirst($method) . 'Output';
        }
        $writer = new TypeWriter($reserved);
        $body =
            'export type Mounts = ' . (implode(' | ', array_map(TypeWriter::literal(...), $mounts)) ?: 'never') . ";\n";
        if ($kind !== Declaration::SERVICE) {
            $body .= 'export type Data = ' . $writer->output($module['load']['shape'] ?? ['k' => 'null']) . ";\n";
            $body .=
                'export type Props = '
                . ($kind === Declaration::LAYOUT ? 'LayoutProps' : 'PageProps')
                . "<Data, Mounts>;\n";
        }
        foreach ($operations as $method => $byMount) {
            $operation = $byMount[array_key_first($byMount)];
            $body .= 'export type ' . ucfirst($method) . 'Input = ' . $writer->input($operation['input']) . ";\n";
            $body .= 'export type ' . ucfirst($method) . 'Output = ' . $writer->output($operation['shape']) . ";\n";
        }
        $imports = array_filter([
            $kind === Declaration::LAYOUT ? 'LayoutProps' : ($kind === Declaration::PAGE ? 'PageProps' : null),
            str_contains($body, 'JsonValue') ? 'JsonValue' : null,
        ]);
        return (
            self::BANNER
            . "\n"
            . ($imports === [] ? '' : 'import type { ' . implode(', ', $imports) . " } from '@crabphp/psx';\n")
            . "\n"
            . $writer->interfaces()
            . ($writer->interfaces() === '' ? '' : "\n")
            . $body
        );
    }

    /**
     * A module's bindings: one name for each query and action, and
     * nothing of what it does.
     *
     * @param array<string, mixed> $module
     * @param array<string, array<string, array<string, mixed>>> $operations
     */
    private static function bindings(string $id, array $module, array $operations, ?string $single): string
    {
        $code = self::BANNER . "\n";
        if ($operations === []) {
            return $code . "export {};\n";
        }
        $code .= "import { action, query } from '@crabphp/psx/bindings';\n";
        $code .= "import type * as T from '@psx/types/{$id}';\n\n";
        foreach ($operations as $method => $byMount) {
            $operation = $byMount[array_key_first($byMount)];
            $types = 'T.' . ucfirst($method) . 'Input, T.' . ucfirst($method) . 'Output';
            $arguments = TypeWriter::literal($id) . ', ' . TypeWriter::literal($method);
            if ($operation['role'] === 'query') {
                $code .= $single === null
                    ? "export const \${$method} = query.scoped<T.Mounts, {$types}>({$arguments});\n"
                    : "export const \${$method} = query.direct<T.Mounts, {$types}>({$arguments}, "
                    . TypeWriter::literal($single)
                    . ");\n";
                continue;
            }
            $mode = $operation['files'] ? 'form' : 'both';
            $code .= $single === null
                ? "export const \${$method} = action.scoped<T.Mounts, {$types}, '{$mode}'>({$arguments});\n"
                : "export const \${$method} = action.direct<T.Mounts, {$types}, '{$mode}'>({$arguments}, "
                . TypeWriter::literal($single)
                . ");\n";
        }
        return $code;
    }

    /**
     * The named routes, as the builders the TSX makes addresses with.
     *
     * @param array<string, array<string, mixed>> $routes
     */
    private static function routes(array $routes): string
    {
        $tree = [];
        $writer = new TypeWriter();
        foreach ($routes as $name => $route) {
            $types = [];
            foreach ($route['nodes'] as $node) {
                $input = $node['load']?->input()['parameters'] ?? [];
                foreach ((array) $input as $parameter => $schema) {
                    $types[$parameter] = $writer->input((array) $schema);
                }
            }
            $parameters = [];
            foreach (array_column($route['segments'], 'name') as $parameter) {
                $parameters[] = TypeWriter::key($parameter) . ': ' . ($types[$parameter] ?? 'string | number');
            }
            $query = [];
            foreach ($route['query'] as $field => $declared) {
                $optional = !$declared['required'] || array_key_exists('default', (array) $declared['schema']);
                $query[] =
                    TypeWriter::key((string) $field)
                    . ($optional ? '?' : '')
                    . ': '
                    . $writer->input((array) $declared['schema']);
            }
            $leaf =
                'route<{ '
                . implode('; ', $parameters)
                . ' }, { '
                . implode('; ', $query)
                . ' }>('
                . TypeWriter::literal($name)
                . ', '
                . self::json($route['segments'], false)
                . ')';
            self::place($tree, explode('.', $name), $leaf);
        }
        return (
            self::BANNER
            . "\nimport { route } from '@crabphp/psx/bindings';\n\nexport const routes = "
            . self::tree($tree, '')
            . ";\n"
        );
    }

    /**
     * @param array<string, array<string, mixed>> $services
     */
    private static function services(array $services): string
    {
        $tree = [];
        foreach ($services as $name => $service) {
            $parameters = array_map(
                static fn(string $parameter): string => TypeWriter::key($parameter) . ': string | number',
                array_column($service['segments'], 'name'),
            );
            $leaf =
                'service<{ '
                . implode('; ', $parameters)
                . ' }, '
                . TypeWriter::literal($name)
                . '>('
                . TypeWriter::literal($name)
                . ', '
                . self::json($service['segments'], false)
                . ')';
            self::place($tree, explode('.', $name), $leaf);
        }
        return (
            self::BANNER
            . "\nimport { service } from '@crabphp/psx/bindings';\n\nexport const services = "
            . self::tree($tree, '')
            . ";\n"
        );
    }

    /**
     * What the page's runtime is told of the application: its routes
     * and where their modules are loaded from, and the address and the
     * shape of each query and action. No class, no file of the server.
     *
     * @param array{routes: array<string, array<string, mixed>>, services: array<string, array<string, mixed>>} $families
     * @param array<string, array<string, array<string, mixed>>> $operations
     * @param array<string, Source> $sources
     */
    private function manifest(array $families, array $operations, array $sources): string
    {
        $routes = [];
        $loaded = [];
        foreach ($families['routes'] as $name => $route) {
            $routes[$name] = [
                'path' => $route['segments'],
                'schema' => $route['schema'],
                'query' => array_keys($route['query']),
                'nodes' => array_map(static fn(array $node): array => [
                    'mount' => $node['mount'],
                    'module' => $node['module'],
                    'layout' => $node['layout'],
                    'shape' => self::bare($node['shape']),
                ], $route['nodes']),
            ];
            foreach ($route['nodes'] as $node) {
                $loaded[$node['module']] = true;
            }
        }
        $services = array_map(static fn(array $service): array => [
            'path' => $service['segments'],
        ], $families['services']);
        $depth = substr_count($this->client, '/') + 1;
        $up = str_repeat('../', $depth);
        $code = self::BANNER . "\nimport type { Manifest } from '@crabphp/psx/bindings';\n";
        if ($this->wrapper !== null) {
            $code .=
                'import Wrapper from '
                . TypeWriter::literal($up . preg_replace('/\.tsx?$/', '', $this->wrapper))
                . ";\n";
        }
        $code .= "\nexport const manifest: Manifest = {\n    protocol: " . self::PROTOCOL . ",\n    modules: {\n";
        foreach (array_keys($loaded) as $id) {
            $code .=
                '        '
                . TypeWriter::literal($id)
                . ': () => import('
                . TypeWriter::literal("./client/{$id}.psx")
                . "),\n";
        }
        $code .= "    },\n    wrapper: " . ($this->wrapper === null ? 'null' : 'Wrapper') . ",\n";
        $code .= '    navigation: ' . TypeWriter::literal($families['navigation']) . ",\n";
        $code .= '    routes: ' . self::json($routes === [] ? new \stdClass() : $routes, false) . ",\n";
        $code .= '    services: ' . self::json($services === [] ? new \stdClass() : $services, false) . ",\n";
        $code .= '    operations: ' . self::json($operations === [] ? new \stdClass() : $operations, false) . ",\n};\n";
        return $code;
    }

    /**
     * A shape without the names of the server's classes.
     *
     * @param array<string, mixed> $shape
     * @return array<string, mixed>
     */
    public static function bare(array $shape): array
    {
        unset($shape['class'], $shape['name']);
        if (isset($shape['of'])) {
            $shape['of'] = self::bare($shape['of']);
        }
        if (isset($shape['props'])) {
            $shape['props'] = $shape['props'] === [] ? new \stdClass() : array_map(self::bare(...), $shape['props']);
        }
        return $shape;
    }

    /**
     * @param array<string, mixed> $tree
     * @param list<string> $path
     */
    private static function place(array &$tree, array $path, string $leaf): void
    {
        $at = &$tree;
        foreach ($path as $part) {
            $at = &$at[$part];
        }
        $at = $leaf;
    }

    /**
     * @param array<string, mixed> $tree
     */
    private static function tree(array $tree, string $indent): string
    {
        if ($tree === []) {
            return '{}';
        }
        $code = "{\n";
        foreach ($tree as $name => $value) {
            $code .=
                "{$indent}    "
                . TypeWriter::key((string) $name)
                . ': '
                . (is_array($value) ? self::tree($value, $indent . '    ') : $value)
                . ",\n";
        }
        return $code . "{$indent}}";
    }

    private static function json(mixed $value, bool $pretty = true): string
    {
        return (
            json_encode(
                $value,
                JSON_THROW_ON_ERROR
                | JSON_UNESCAPED_SLASHES
                | JSON_UNESCAPED_UNICODE
                | ($pretty ? JSON_PRETTY_PRINT : 0),
            ) . ($pretty ? "\n" : '')
        );
    }

    /**
     * Writes a file when what it holds has changed, so that nothing
     * watching it is told of a change that is none.
     */
    public static function write(string $path, string $content): void
    {
        if (is_file($path) && file_get_contents($path) === $content) {
            return;
        }
        $directory = dirname($path);
        if (!is_dir($directory) && !mkdir($directory, 0o755, true) && !is_dir($directory)) {
            throw new PsxException("The folder {$directory} cannot be made.");
        }
        $temporary = $path . '.' . bin2hex(random_bytes(4)) . '.tmp';
        if (file_put_contents($temporary, $content) === false || !rename($temporary, $path)) {
            @unlink($temporary);
            throw new PsxException("The file {$path} cannot be written.");
        }
    }

    /**
     * Empties a folder of this compiler's.
     */
    public static function fresh(string $directory): void
    {
        if (!is_dir($directory)) {
            return;
        }
        $iterator = new \RecursiveIteratorIterator(
            new \RecursiveDirectoryIterator($directory, \FilesystemIterator::SKIP_DOTS),
            \RecursiveIteratorIterator::CHILD_FIRST,
        );
        foreach ($iterator as $file) {
            $file->isDir() && !$file->isLink() ? rmdir($file->getPathname()) : unlink($file->getPathname());
        }
    }

    /**
     * Removes the generated files a compile no longer writes.
     *
     * @param list<string> $keep Paths inside the folder.
     */
    private static function prune(string $root, array $keep): void
    {
        if (!is_dir($root)) {
            return;
        }
        $keep = array_flip($keep);
        $iterator = new \RecursiveIteratorIterator(
            new \RecursiveDirectoryIterator($root, \FilesystemIterator::SKIP_DOTS),
            \RecursiveIteratorIterator::CHILD_FIRST,
        );
        foreach ($iterator as $file) {
            $relative = substr($file->getPathname(), strlen($root) + 1);
            if ($file->isDir()) {
                @rmdir($file->getPathname());
            } elseif (
                !isset($keep[$relative])
                && preg_match('~^(?:client|types|server)/|^(?:routes|services|manifest)\.ts$|^php/~', $relative) === 1
            ) {
                unlink($file->getPathname());
            }
        }
    }
}
